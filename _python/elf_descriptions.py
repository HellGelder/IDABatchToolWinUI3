def _normalize(name: Optional[str]) -> str:
    """Приводит имя секции/сегмента к виду, пригодному для поиска в словаре."""
    return (name or "").strip()


def describe_section(name: Optional[str], section_type: Optional[str] = None) -> str:
    """Возвращает словесное назначение секции ELF.

    Порядок поиска: точное имя → семейство по префиксу → тип секции →
    общее описание. Всегда возвращает непустую строку, чтобы в отчёте не
    оставалось пустых ячеек.

    Args:
        name: имя секции (например, ``.text``).
        section_type: тип секции из ``sh_type`` (например, ``PROGBITS``).

    Returns:
        Описание назначения на русском языке.
    """
    key = _normalize(name)
    if key in SECTION_DESCRIPTIONS:
        return SECTION_DESCRIPTIONS[key]
    for prefix, description in SECTION_PREFIX_DESCRIPTIONS:
        if key.startswith(prefix):
            return description
    type_key = _normalize(section_type).upper()
    if type_key in SECTION_TYPE_DESCRIPTIONS:
        return SECTION_TYPE_DESCRIPTIONS[type_key]
    return "Служебная секция файла."


def describe_segment(segment_type: Optional[str]) -> str:
    """Возвращает словесное назначение сегмента (программного заголовка) ELF.

    Args:
        segment_type: тип сегмента (например, ``LOAD``).

    Returns:
        Описание назначения на русском языке.
    """
    key = _normalize(segment_type).upper()
    if key in SEGMENT_DESCRIPTIONS:
        return SEGMENT_DESCRIPTIONS[key]
    return "Служебный сегмент загрузчика."
